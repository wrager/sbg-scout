/** Mirror repository skills for Claude Code without symlinks or npm dependencies. */
import { lstat, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILL_NAME = /^scout-[a-z0-9]+(?:-[a-z0-9]+)*$/;
const MARKER = '.generated';

async function directoryExists(path) {
  try {
    const entry = await lstat(path);
    if (entry.isSymbolicLink() || !entry.isDirectory()) {
      throw new Error(`Expected a regular directory, not a link: ${path}`);
    }
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

async function readTree(directory, prefix = '') {
  const files = new Map();
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    const key = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) throw new Error(`Links are not supported in shared skills: ${path}`);
    if (entry.isDirectory()) {
      for (const [name, content] of await readTree(path, key)) files.set(name, content);
    } else if (entry.isFile()) {
      files.set(key, await readFile(path));
    } else {
      throw new Error(`Expected a regular skill file: ${path}`);
    }
  }
  return files;
}

function marker(name) {
  return Buffer.from(`Generated by scripts/syncAgentSkills.mjs from .agents/skills/${name}/\n`);
}

function equalTrees(left, right) {
  return left.size === right.size && [...left].every(([name, content]) => right.has(name) && content.equals(right.get(name)));
}

export async function syncAgentSkills({ root = ROOT, check = false } = {}) {
  root = resolve(root);
  const source = join(root, '.agents', 'skills');
  const target = join(root, '.claude', 'skills');
  await directoryExists(join(root, '.agents'));
  if (!(await directoryExists(source))) throw new Error(`Shared skills directory is missing: ${source}`);
  await directoryExists(join(root, '.claude'));
  const targetExists = await directoryExists(target);

  // Read and validate every planned change before writing or deleting anything.
  const expected = new Map();
  for (const name of (await readdir(source)).sort()) {
    if (!SKILL_NAME.test(name) || name.length > 64) throw new Error(`Invalid shared skill directory: ${name}`);
    const directory = join(source, name);
    await directoryExists(directory);
    const files = await readTree(directory);
    if (!files.has('SKILL.md')) throw new Error(`Missing SKILL.md: ${directory}`);
    if (files.has(MARKER)) throw new Error(`Reserved generated marker in source: ${directory}`);
    files.set(MARKER, marker(name));
    expected.set(name, files);
  }

  const actual = new Map();
  if (targetExists) {
    for (const name of (await readdir(target)).sort()) {
      if (!SKILL_NAME.test(name)) continue;
      const directory = join(target, name);
      await directoryExists(directory);
      const files = await readTree(directory);
      if (!files.get(MARKER)?.equals(marker(name))) {
        if (expected.has(name)) throw new Error(`Refusing to overwrite an unmanaged skill: ${directory}`);
        continue;
      }
      actual.set(name, files);
    }
  }

  const names = [...new Set([...expected.keys(), ...actual.keys()])].sort();
  const changed = names.filter((name) => !equalTrees(expected.get(name) ?? new Map(), actual.get(name) ?? new Map()));
  if (check) return changed;

  for (const name of changed) {
    const directory = join(target, name);
    // Only owned, preflighted directories directly inside .claude/skills may be removed.
    if (relative(target, directory) !== name) throw new Error(`Unsafe output directory: ${directory}`);
    if (actual.has(name)) await rm(directory, { recursive: true });
    if (!expected.has(name)) continue;
    for (const [file, content] of expected.get(name)) {
      const output = join(directory, file);
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, content);
    }
  }
  return changed;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const argumentsList = process.argv.slice(2);
    if (argumentsList.some((argument) => argument !== '--check') || argumentsList.length > 1) {
      throw new Error('Usage: node scripts/syncAgentSkills.mjs [--check]');
    }
    const check = argumentsList.includes('--check');
    const changed = await syncAgentSkills({ check });
    if (check && changed.length) {
      console.error(`Claude skills are out of sync: ${changed.join(', ')}. Run node scripts/syncAgentSkills.mjs`);
      process.exitCode = 1;
    } else {
      console.log(changed.length ? `Updated Claude skills: ${changed.join(', ')}` : 'Shared agent skills are in sync.');
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
